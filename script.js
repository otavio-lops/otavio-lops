function initializeLanguagePicker() {
  const $ = window.jQuery;
  if (!$?.fn.select2) return;
  const names = { pt: "Português", en: "English", es: "Español" };
  const flags = { pt: "br", en: "us", es: "es" };
  function renderLanguage(option, compact = false) {
    if (!option.id) return option.text;
    const language =
      compact && option.id === "auto" ? activeLanguage : option.id;
    const row = document.createElement("span");
    row.className = `language-choice${language === "auto" ? " language-auto" : ""}`;
    row.dataset.shortLabel = language.toUpperCase();
    if (flags[language]) {
      const flag = document.createElement("img");
      flag.src = new URL(
        `imagens/flags/${flags[language]}.webp`,
        siteRoot,
      ).href;
      flag.alt = "";
      flag.width = 24;
      flag.height = 16;
      row.append(flag);
    } else {
      const globe = document.createElement("span");
      globe.className = "language-globe";
      globe.setAttribute("aria-hidden", "true");
      globe.textContent = "◎";
      row.append(globe);
    }
    const label =
      language === "auto"
        ? messages.automatic[columns[activeLanguage]]
        : names[language];
    const labelElement = document.createElement("span");
    labelElement.className = "language-choice-label";
    labelElement.textContent = label;
    row.append(labelElement);
    return $(row);
  }
  $(languageSelect)
    .select2({
      width: "100%",
      dropdownParent: $(".language-picker"),
      templateResult: (option) => renderLanguage(option),
      templateSelection: (option) => renderLanguage(option, true),
      language: { noResults: () => messages.language[columns[activeLanguage]] },
    })
    .on("select2:select", () =>
      languageSelect.dispatchEvent(new Event("change", { bubbles: true })),
    );
  $(languageSelect).on("select2:open", () => {
    $(".language-picker .select2-dropdown")
      .parent()
      .addClass("language-menu-position");
    const search = document.querySelector(
      ".language-picker .select2-search__field",
    );
    search?.setAttribute(
      "aria-label",
      messages.language[columns[activeLanguage]],
    );
    search?.focus();
  });
  syncLanguagePicker();
}

