let detectionVersion = 0;
async function detectLanguage() {
  const version = ++detectionVersion;
  applyLanguage(browserLanguage());
  for (const url of ["https://ipapi.co/json/", "https://ipwho.is/"]) {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 2500);
    try {
      const response = await fetch(url, { signal: controller.signal });
      if (!response.ok) continue;
      const location = await response.json();
      if (!location.country_code) continue;
      if (version === detectionVersion && languageSelect.value === "auto")
        applyLanguage(
          countryLanguage[location.country_code.toUpperCase()] ||
            browserLanguage(),
        );
      return;
    } catch (_) {
      /* Try the second provider, then keep browser language. */
    } finally {
      clearTimeout(timeout);
    }
  }
}
