// Use the stationary figure for coordinates so the tilted image never jitters.
const tiltPreference = matchMedia(
  "(hover: hover) and (pointer: fine) and (prefers-reduced-motion: no-preference)",
);
document.querySelectorAll(".case-visual, .hero-portrait").forEach((figure) => {
  const image =
    figure.querySelector(".image-link") || figure.querySelector("img");
  let frame = 0;
  function resetTilt() {
    cancelAnimationFrame(frame);
    frame = 0;
    figure.removeAttribute("data-tilting");
    figure.style.removeProperty("--tilt-x");
    figure.style.removeProperty("--tilt-y");
  }
  figure.addEventListener("pointermove", (event) => {
    if (!tiltPreference.matches || event.pointerType !== "mouse") return;
    const bounds = figure.getBoundingClientRect();
    const x = Math.max(
      -1,
      Math.min(1, ((event.clientX - bounds.left) / bounds.width) * 2 - 1),
    );
    const y = Math.max(
      -1,
      Math.min(1, ((event.clientY - bounds.top) / image.offsetHeight) * 2 - 1),
    );
    cancelAnimationFrame(frame);
    frame = requestAnimationFrame(() => {
      figure.setAttribute("data-tilting", "");
      figure.style.setProperty("--tilt-x", `${y * 6}deg`);
      figure.style.setProperty("--tilt-y", `${-x * 6}deg`);
      frame = 0;
    });
  });
  figure.addEventListener("pointerleave", resetTilt);
  figure.addEventListener("pointercancel", resetTilt);
  tiltPreference.addEventListener("change", resetTilt);
});

