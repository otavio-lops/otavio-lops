function updateThemeButton() {
  const dark = document.documentElement.dataset.theme === "dark";
  const label =
    messages[dark ? "theme_light" : "theme_dark"][columns[activeLanguage]];
  themeButton.setAttribute("aria-label", label);
  themeButton.setAttribute("title", label);
  themeButton.setAttribute("aria-pressed", String(dark));
  document.querySelector('meta[name="theme-color"]').content = dark
    ? "#000000"
    : "#f3f4f5";
}
function applyLanguage(language) {
  activeLanguage = language;
  const column = columns[language];
  document.documentElement.lang = locales[language];
  document.title =
    messages[
      document.body.dataset.project ? "detail_page_title" : "page_title"
    ][column];
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = messages[element.dataset.i18n][column];
  });
  document.querySelectorAll("[data-i18n-meta]").forEach((element) => {
    element.content = messages[element.dataset.i18nMeta][column];
  });
  for (const attribute of ["aria", "alt"]) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((element) => {
      element.setAttribute(
        attribute === "aria" ? "aria-label" : "alt",
        messages[
          element.dataset[attribute === "aria" ? "i18nAria" : "i18nAlt"]
        ][column],
      );
    });
  }
  for (const selector of [
    'meta[property="og:title"]',
    'meta[name="twitter:title"]',
  ])
    document.querySelector(selector).content =
      messages[
        document.body.dataset.project ? "detail_page_title" : "page_title"
      ][column];
  for (const selector of [
    'meta[name="description"]',
    'meta[property="og:description"]',
    'meta[name="twitter:description"]',
  ])
    document.querySelector(selector).content =
      messages[
        document.body.dataset.project
          ? "detail_page_description"
          : "page_description"
      ][column];
  document.querySelector('meta[property="og:locale"]').content = locales[
    language
  ].replace("-", "_");
  document
    .querySelectorAll('meta[property="og:locale:alternate"]')
    .forEach((element, index) => {
      element.content = Object.values(locales)
        .filter((value) => value !== locales[language])
        [index].replace("-", "_");
    });
  updateThemeButton();
  syncLanguagePicker();
  renderContactState();
}

function renderContactState() {
  const form = document.querySelector("#contact-form");
  if (!form) return;
  const state = form.dataset.state || "idle";
  const pending = state === "sending";
  const button = form.querySelector('[type="submit"]');
  button.disabled = pending;
  button.querySelector("[data-i18n]").textContent =
    messages[pending ? "form_sending" : "form_send"][columns[activeLanguage]];
  form.setAttribute("aria-busy", String(pending));
  const status = document.querySelector("#contact-status");
  status.textContent =
    state === "success" || state === "error"
      ? messages[`form_${state}`][columns[activeLanguage]]
      : "";
}

document
  .querySelector("#contact-form")
  .addEventListener("submit", async (event) => {
    event.preventDefault();
    const form = event.currentTarget;
    if (form.dataset.state === "sending" || !form.reportValidity()) return;
    form.dataset.state = "sending";
    renderContactState();
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 15000);
    try {
      const response = await fetch(form.action, {
        method: "POST",
        body: new FormData(form),
        headers: { Accept: "application/json" },
        signal: controller.signal,
      });
      if (!response.ok) throw new Error("Form submission failed");
      form.reset();
      form.dataset.state = "success";
    } catch (_) {
      form.dataset.state = "error";
    } finally {
      clearTimeout(timeout);
      renderContactState();
    }
  });

