let languagePickerScrollTop = null;
let languagePickerWasManuallyScrolled = false;
let languagePickerInteractionId = 0;
function trackManualLanguagePickerScroll() {
  if (languagePickerScrollTop === null) return;
  languagePickerWasManuallyScrolled = true;
  requestAnimationFrame(() => {
    if (languagePickerScrollTop === null) return;
    languagePickerScrollTop = window.scrollY;
    if (
      !document.querySelector(".language-picker .select2-container--open")
    )
      restoreLanguagePickerScroll();
  });
}
window.addEventListener(
  "wheel",
  trackManualLanguagePickerScroll,
  { passive: true },
);
window.addEventListener(
  "touchmove",
  trackManualLanguagePickerScroll,
  { passive: true },
);
function restoreLanguagePickerScroll(clearAfter = false) {
  const top = languagePickerScrollTop;
  if (top === null) return;
  if (clearAfter) {
    const interactionId = languagePickerInteractionId;
    setTimeout(() => {
      if (
        languagePickerInteractionId === interactionId &&
        !document.querySelector(".language-picker .select2-container--open")
      ) {
        languagePickerScrollTop = null;
        languagePickerWasManuallyScrolled = false;
      }
    }, 150);
  }
  requestAnimationFrame(() => {
    if (languagePickerScrollTop !== top) return;
    window.scrollTo({ top, behavior: "instant" });
    requestAnimationFrame(() => {
      if (languagePickerScrollTop !== top) return;
      window.scrollTo({ top, behavior: "instant" });
    });
  });
}
function rememberLanguagePickerScroll(force = false) {
  if (!force && languagePickerScrollTop !== null) return;
  languagePickerScrollTop = window.scrollY;
  languagePickerWasManuallyScrolled = false;
  languagePickerInteractionId += 1;
}

